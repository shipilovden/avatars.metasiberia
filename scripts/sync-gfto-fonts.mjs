import { mkdir, readdir, rm, stat, unlink, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(SCRIPT_DIR, "..");

const GFTO_EDITOR_URL = "https://gfto.ru/png-text-effect/editor.html";
const GFTO_FONTS_CSS_URL = "https://gfto.ru/gtanim/fonts.css";
const OUTPUT_FONT_DIR = path.join(REPO_ROOT, "public", "fonts", "gfto");
const OUTPUT_FONT_CSS = path.join(REPO_ROOT, "src", "gfto-fonts.css");
const OUTPUT_FONT_OPTIONS = path.join(
  REPO_ROOT,
  "src",
  "components",
  "uv-editor-port",
  "gfto-font-options.ts"
);

const OPTION_REGEX = /<option[^>]*style="font-family:\s*([^;"]+)/g;
const FONT_FACE_BLOCK_REGEX = /@font-face\s*\{[\s\S]*?\}/g;
const FONT_SOURCE_REGEX = /url\('([^']+)'\)\s*format\('([^']+)'\)/g;

const fetchText = async (url) => {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`Failed to fetch ${url}: ${response.status} ${response.statusText}`);
  }

  return response.text();
};

const parseFontNames = (editorHtml) => {
  const names = [];
  const seen = new Set();
  for (const match of editorHtml.matchAll(OPTION_REGEX)) {
    const fontFamily = match[1]?.trim();
    if (!fontFamily || seen.has(fontFamily)) {
      continue;
    }

    seen.add(fontFamily);
    names.push(fontFamily);
  }

  return names;
};

const parseFontFaceMap = (fontCss) => {
  const faces = new Map();
  for (const blockMatch of fontCss.matchAll(FONT_FACE_BLOCK_REGEX)) {
    const block = blockMatch[0];
    const fontFamily = block.match(/font-family:\s*'([^']+)'/)?.[1]?.trim();
    if (!fontFamily || faces.has(fontFamily)) {
      continue;
    }

    const sources = [...block.matchAll(FONT_SOURCE_REGEX)]
      .map((match) => ({
        remoteUrl: new URL(match[1], GFTO_FONTS_CSS_URL).href,
        format: match[2]?.trim() || "",
      }))
      .filter((source) => source.remoteUrl.endsWith(".woff") || source.remoteUrl.endsWith(".ttf"));
    if (!sources.length) {
      continue;
    }

    faces.set(fontFamily, {
      fontFamily,
      sources,
      fontStyle: block.match(/font-style:\s*([^;]+);/)?.[1]?.trim() || "normal",
      fontWeight: block.match(/font-weight:\s*([^;]+);/)?.[1]?.trim() || "normal",
    });
  }

  return faces;
};

const ensureCleanDirectory = async (directory) => {
  await mkdir(directory, { recursive: true });
  const entries = await readdir(directory, { withFileTypes: true });
  await Promise.all(
    entries.map((entry) =>
      entry.isDirectory()
        ? rm(path.join(directory, entry.name), { recursive: true, force: true })
        : unlink(path.join(directory, entry.name)).catch(() => undefined)
    )
  );
};

const allocateOutputFileNames = (facesInUse) => {
  const usedNames = new Map();
  for (const face of facesInUse) {
    const remotePath = new URL(face.resolvedRemoteUrl).pathname;
    const parsed = path.parse(remotePath);
    let fileName = `${parsed.name}${parsed.ext || ".woff"}`;
    let suffix = 2;
    while (usedNames.has(fileName) && usedNames.get(fileName) !== face.resolvedRemoteUrl) {
      fileName = `${parsed.name}-${suffix}${parsed.ext || ".woff"}`;
      suffix += 1;
    }

    usedNames.set(fileName, face.resolvedRemoteUrl);
    face.localFileName = fileName;
  }
};

const resolveFontSources = async (facesInUse) => {
  const concurrency = 8;
  let index = 0;

  const worker = async () => {
    while (index < facesInUse.length) {
      const currentIndex = index;
      index += 1;
      const face = facesInUse[currentIndex];
      let resolvedSource = null;
      for (const source of face.sources) {
        const response = await fetch(source.remoteUrl);
        if (!response.ok) {
          continue;
        }

        resolvedSource = {
          ...source,
          buffer: Buffer.from(await response.arrayBuffer()),
        };
        break;
      }

      if (!resolvedSource) {
        const attempted = face.sources.map((source) => source.remoteUrl).join(", ");
        throw new Error(`Failed to download ${face.fontFamily}. Tried: ${attempted}`);
      }

      face.resolvedRemoteUrl = resolvedSource.remoteUrl;
      face.resolvedFormat = resolvedSource.format === "truetype" ? "truetype" : "woff";
      face.buffer = resolvedSource.buffer;
    }
  };

  await Promise.all(
    Array.from({ length: Math.min(concurrency, Math.max(1, facesInUse.length)) }, () => worker())
  );
};

const downloadFonts = async (facesInUse) =>
  Promise.all(
    facesInUse.map((face) => writeFile(path.join(OUTPUT_FONT_DIR, face.localFileName), face.buffer))
  );

const generateFontCss = (facesInUse) => {
  const header =
    "/* Generated by scripts/sync-gfto-fonts.mjs from gfto.ru. Verify font licenses before redistribution. */\n";
  const blocks = facesInUse.map(
    (face) => `@font-face {
  font-family: ${JSON.stringify(face.fontFamily)};
  src: url("/fonts/gfto/${face.localFileName}") format("${face.resolvedFormat}");
  font-style: ${face.fontStyle};
  font-weight: ${face.fontWeight};
  font-display: swap;
}`
  );

  return `${header}\n${blocks.join("\n\n")}\n`;
};

const generateFontOptionsModule = (fontNames) => {
  const header =
    "// Generated by scripts/sync-gfto-fonts.mjs from gfto.ru. Verify font licenses before redistribution.\n";
  const rows = fontNames.map(
    (fontName) =>
      `  { value: ${JSON.stringify(JSON.stringify(fontName))}, label: ${JSON.stringify(fontName)} },`
  );

  return `${header}
export type TextFontOption = {
  value: string;
  label: string;
};

export const GFTO_TEXT_FONT_OPTIONS: TextFontOption[] = [
${rows.join("\n")}
];
`;
};

const main = async () => {
  await mkdir(path.dirname(OUTPUT_FONT_CSS), { recursive: true });
  await mkdir(path.dirname(OUTPUT_FONT_OPTIONS), { recursive: true });

  const [editorHtml, fontCss] = await Promise.all([
    fetchText(GFTO_EDITOR_URL),
    fetchText(GFTO_FONTS_CSS_URL),
  ]);

  const fontNames = parseFontNames(editorHtml);
  const faceMap = parseFontFaceMap(fontCss);
  const facesInUse = fontNames.map((fontName) => {
    const face = faceMap.get(fontName);
    if (!face) {
      throw new Error(`Font "${fontName}" was found in the editor, but not in fonts.css`);
    }

    return { ...face, localFileName: "" };
  });

  await resolveFontSources(facesInUse);
  await ensureCleanDirectory(OUTPUT_FONT_DIR);
  allocateOutputFileNames(facesInUse);
  await downloadFonts(facesInUse);

  await Promise.all([
    writeFile(OUTPUT_FONT_CSS, generateFontCss(facesInUse)),
    writeFile(OUTPUT_FONT_OPTIONS, generateFontOptionsModule(fontNames)),
  ]);

  const downloaded = await readdir(OUTPUT_FONT_DIR);
  const totalBytes = await Promise.all(
    downloaded.map(async (fileName) => (await stat(path.join(OUTPUT_FONT_DIR, fileName))).size)
  );

  console.log(
    `[gfto-fonts] synced ${fontNames.length} fonts, downloaded ${downloaded.length} files, total ${(totalBytes.reduce((sum, size) => sum + size, 0) / (1024 * 1024)).toFixed(2)} MiB`
  );
};

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
